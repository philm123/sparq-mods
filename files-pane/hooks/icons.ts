const fileIconId = (name: string) => {
  const lower = name.toLowerCase()

  if (BY_NAME[lower]) return BY_NAME[lower]

  for (const [prefix, id] of BY_PREFIX) if (lower.startsWith(prefix)) return id

  // `a.test.tsx` tries `test.tsx`, then `tsx`.
  const parts = lower.split('.')

  for (let i = 1; i < parts.length; i++) {
    const id = BY_EXT[parts.slice(i).join('.')]

    if (id) return id
  }

  return 'default-file'
}

const folderIconId = (name: string, isOpen: boolean) => {
  const id = BY_FOLDER[name.toLowerCase()]

  if (id) return isOpen ? `${id}-opened` : id

  return isOpen ? 'default-folder-opened' : 'default-folder'
}

// The SVG document a file or folder wears.
export const fileIcon = (name: string) => SVGS[fileIconId(name)] ?? SVGS['default-file']!

export const folderIcon = (name: string, isOpen: boolean) =>
  SVGS[folderIconId(name, isOpen)] ?? SVGS[isOpen ? 'default-folder-opened' : 'default-folder']!

// Every id the tables above name, for the generator that writes icon-svgs.ts.
export const ICON_IDS = [
  ...new Set([
    ...Object.values(BY_NAME),
    ...BY_PREFIX.map(([, id]) => id),
    ...Object.values(BY_EXT),
    ...Object.values(BY_FOLDER).flatMap(id => [id, `${id}-opened`]),
    'default-file',
    'default-folder',
    'default-folder-opened',
  ]),
]
